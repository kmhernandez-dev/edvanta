export const RUTA_COMUNIDAD = '/comunidad';
export const RUTA_TEMAS = '/comunidad/temas';
export const RUTA_WEBINARS = '/webinars';

export const rutaCluster = (cluster) => `${RUTA_TEMAS}/${typeof cluster === 'string' ? cluster : cluster.slug}`;
export const rutaTema = (tema) => `${RUTA_TEMAS}/${tema.cluster}/${tema.slug}`;
export const rutaWebinar = (webinar) => `${RUTA_WEBINARS}/${typeof webinar === 'string' ? webinar : webinar.slug}`;

export const clusterPorSlug = (slug) => CLUSTERS.find((c) => c.slug === slug) || null;
export const temaPorSlug = (clusterSlug, temaSlug) => TEMAS.find((t) => t.cluster === clusterSlug && t.slug === temaSlug) || null;
export const webinarPorSlug = (slug) => WEBINARS.find((w) => w.slug === slug) || null;

export const temasDeCluster = (clusterSlug) => TEMAS.filter((t) => t.cluster === clusterSlug);
export const webinarsDeCluster = (clusterSlug) => WEBINARS.filter((w) => w.cluster === clusterSlug);
export const webinarsDelTema = (tema) => WEBINARS.filter((w) => w.slug === tema.webinar || (w.temas || []).includes(tema.slug));

export const temasRelacionados = (tema, limite = 3) => TEMAS
  .filter((t) => t.slug !== tema.slug)
  .sort((a, b) => Number(b.cluster === tema.cluster) - Number(a.cluster === tema.cluster))
  .slice(0, limite);

export const webinarsRelacionados = (webinar, limite = 3) => {
  const propios = new Set(webinar.temas || []);
  return WEBINARS
    .filter((w) => w.slug !== webinar.slug)
    .sort((a, b) => {
      const aComun = (a.temas || []).filter((t) => propios.has(t)).length + Number(a.cluster === webinar.cluster);
      const bComun = (b.temas || []).filter((t) => propios.has(t)).length + Number(b.cluster === webinar.cluster);
      return bComun - aComun;
    })
    .slice(0, limite);
};

