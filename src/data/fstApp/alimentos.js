export const foodAliasIndex = (() => {
  const index = new Map();
  for (const food of foodKnowledge) {
    for (const alias of [food.name, ...food.aliases]) {
      index.set(alias.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, ''), food);
    }
  }
  return index;
})();

export function findFood(query) {
  const normalized = String(query || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
  if (!normalized) return null;
  if (foodAliasIndex.has(normalized)) return foodAliasIndex.get(normalized);
  for (const [alias, food] of foodAliasIndex.entries()) {
    if (alias.length >= 4 && normalized.includes(alias)) return food;
  }
  return null;
}

