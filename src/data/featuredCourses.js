export function trackAffiliateCourseClick(course, options = {}) {
  const payload = {
    course_name: course.title,
    course_code: course.courseCode,
    page_location: typeof window !== 'undefined' ? window.location.href : '',
    source_section: options.sourceSection || 'unknown',
    article_slug: options.articleSlug || null,
    timestamp: new Date().toISOString(),
  };

  if (typeof window !== 'undefined') {
    window.dataLayer = window.dataLayer || [];
    window.dataLayer.push({ event: 'affiliate_course_click', ...payload });
    if (typeof window.gtag === 'function') {
      window.gtag('event', 'affiliate_course_click', payload);
    }
  }

  return payload;
}
